def _recent(data: dict, splits: dict[int, dict] | None = None, splits_url: str = "") -> str:
    runs = _runs(data)
    if not runs:
        return _no_data()

    # Last 5 activities
    rows = runs[:5]
    return _activity_table(rows, splits, splits_url)


