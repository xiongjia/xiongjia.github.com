"""MkDocs macros for running tracking.

Reads the local data file `docs/notes/health/data/running.yml` (generated by
`uv run poe sync-running` from the deployed running_page site) — no network
access at build/serve time. If the data file is missing, every macro renders a
friendly hint instead of failing.
"""

