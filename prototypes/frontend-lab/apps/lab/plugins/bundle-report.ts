import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

import { labRoot, relToPrototype } from './frontmatter.ts'

/*
 * Bundle report.
 *
 * `vite build` prints chunk sizes once, at the end of a scroll of output. This module turns the same
 * numbers into a file that can be compared between builds, and into a budget check that fails
 * loudly when a chunk grows past what the lab agreed to pay for.
 *
 * Two lessons from B15 shaped it:
 *
 *   - **Raw size is the wrong number.** A 450 kB chunk of React runtime gzips to 150 kB; comparing
 *     raw bytes across libraries overstates the expensive ones.
 *   - **A chunk name is a contract.** The chart renderers live in their own lazy chunks precisely so
 *     their cost is attributable here (`recharts-chart-*`, `chartjs-chart-*`) instead of being
 *     hidden inside a demo chunk.
 */

export type Asset = {
  /** File name inside `dist/assets`. */
  file: string
  kind: 'js' | 'css'
  bytes: number
  gzip: number
}

export type Budget = {
  /** Fail when the whole JS payload (gzip) exceeds this. */
  totalJsGzip?: number
  /** Fail when one JS chunk (gzip) exceeds this. */
  chunkJsGzip?: number
}

export const defaultBudgets: Budget = {
  // Set from the B17 baseline; a deliberate increase should update this number, not slip through.
  totalJsGzip: 800_000,
  chunkJsGzip: 200_000,
}

const defaultDistDir = path.join(labRoot, 'dist')
const defaultReportFile = path.join(labRoot, 'bundle-report.md')

export async function measureAssets(distDir: string = defaultDistDir): Promise<Asset[]> {
  const assetsDir = path.join(distDir, 'assets')
  const names = (await readdir(assetsDir)).sort((a, b) => a.localeCompare(b))

  const assets: Asset[] = []
  for (const name of names) {
    const kind = name.endsWith('.js') ? 'js' : name.endsWith('.css') ? 'css' : undefined
    if (!kind) continue

    const bytes = await readFile(path.join(assetsDir, name))
    assets.push({ file: name, kind, bytes: bytes.byteLength, gzip: gzipSync(bytes).byteLength })
  }

  return assets
}

function kb(bytes: number): string {
  return `${(bytes / 1000).toFixed(1)} kB`
}

function table(rows: string[][]): string {
  const [head, ...body] = rows
  if (!head) return ''
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...body.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n')
}

/** Group the built assets into the sections the report shows. */
export function groupAssets(assets: Asset[]) {
  const js = assets.filter((asset) => asset.kind === 'js')
  const css = assets.filter((asset) => asset.kind === 'css')
  const totalGzip = js.reduce((sum, asset) => sum + asset.gzip, 0)

  const named = (pattern: RegExp) =>
    js.filter((asset) => pattern.test(asset.file)).sort((a, b) => b.gzip - a.gzip)

  return {
    js,
    css,
    totalGzip,
    // Vite's entry chunk, the shared React chunk, and the editor/syntax chunk are not per-demo.
    shared: named(/^(index|react|src|use-reduced-motion)-/),
    charts: named(/^(recharts-chart|chartjs-chart)-/),
    demos: js.filter((asset) => asset.file.startsWith('demo-')).sort((a, b) => b.gzip - a.gzip),
    notes: js.filter((asset) => asset.file.startsWith('notes')),
  }
}

/** Violations of the budgets, ready to print. */
export function budgetProblems(assets: Asset[], budget: Budget = defaultBudgets): string[] {
  const problems: string[] = []
  const js = assets.filter((asset) => asset.kind === 'js')
  const totalGzip = js.reduce((sum, asset) => sum + asset.gzip, 0)

  if (budget.totalJsGzip !== undefined && totalGzip > budget.totalJsGzip) {
    problems.push(`total JS is ${kb(totalGzip)} gzip, over the ${kb(budget.totalJsGzip)} budget`)
  }

  if (budget.chunkJsGzip !== undefined) {
    for (const asset of js) {
      if (asset.gzip > budget.chunkJsGzip) {
        problems.push(`${asset.file} is ${kb(asset.gzip)} gzip, over the per-chunk budget`)
      }
    }
  }

  return problems
}

/** Markdown report: totals, shared chunks, the chart renderers, the heaviest demos. */
export function renderReport(assets: Asset[], generatedAt: string): string {
  const groups = groupAssets(assets)
  const cssGzip = groups.css.reduce((sum, asset) => sum + asset.gzip, 0)

  const lines = [
    '<!-- Generated by `pnpm bundle:report` (apps/lab/plugins/bundle-report.ts). Do not edit. -->',
    '',
    '# Bundle report',
    '',
    `Generated: ${generatedAt}`,
    '',
    '## Totals',
    '',
    table([
      ['Kind', 'Files', 'Raw', 'Gzip'],
      [
        'JS',
        String(groups.js.length),
        kb(groups.js.reduce((sum, a) => sum + a.bytes, 0)),
        kb(groups.totalGzip),
      ],
      [
        'CSS',
        String(groups.css.length),
        kb(groups.css.reduce((sum, a) => sum + a.bytes, 0)),
        kb(cssGzip),
      ],
    ]),
    '',
    '## Shared chunks (first load)',
    '',
    table([
      ['Chunk', 'Raw', 'Gzip'],
      ...groups.shared.map((asset) => [asset.file, kb(asset.bytes), kb(asset.gzip)]),
    ]),
    '',
    '## Chart renderers (lazy)',
    '',
    table([
      ['Chunk', 'Raw', 'Gzip'],
      ...groups.charts.map((asset) => [asset.file, kb(asset.bytes), kb(asset.gzip)]),
    ]),
    '',
    '## Heaviest demo chunks',
    '',
    table([
      ['Chunk', 'Raw', 'Gzip'],
      ...groups.demos.slice(0, 10).map((asset) => [asset.file, kb(asset.bytes), kb(asset.gzip)]),
    ]),
    '',
    '## Budgets',
    '',
    `Total JS gzip budget: ${kb(defaultBudgets.totalJsGzip ?? 0)} · per-chunk gzip budget: ${kb(
      defaultBudgets.chunkJsGzip ?? 0,
    )}`,
    '',
    `Current total JS gzip: ${kb(groups.totalGzip)}`,
    '',
  ]

  return lines.join('\n')
}

export type ReportResult = {
  assets: Asset[]
  reportFile: string
  problems: string[]
}

export async function writeBundleReport({
  distDir = defaultDistDir,
  reportFile = defaultReportFile,
  budget = defaultBudgets,
  generatedAt = new Date().toISOString().slice(0, 10),
}: {
  distDir?: string
  reportFile?: string
  budget?: Budget
  generatedAt?: string
} = {}): Promise<ReportResult> {
  const assets = await measureAssets(distDir)
  const problems = budgetProblems(assets, budget)

  await writeFile(reportFile, `${renderReport(assets, generatedAt)}\n`, 'utf8')
  return { assets, reportFile, problems }
}

const invokedDirectly =
  process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (invokedDirectly) {
  try {
    const { assets, reportFile, problems } = await writeBundleReport()
    const groups = groupAssets(assets)

    console.log(`bundle report: ${assets.length} asset(s) -> ${relToPrototype(reportFile)}`)
    console.log(`  total JS gzip: ${kb(groups.totalGzip)}`)
    for (const asset of [...groups.shared, ...groups.charts]) {
      console.log(`  ${asset.file.padEnd(38)} ${kb(asset.gzip).padStart(9)} gzip`)
    }

    if (problems.length > 0) {
      console.error(`\nbundle budget: ${problems.length} problem(s)`)
      for (const problem of problems) console.error(`  · ${problem}`)
      process.exit(1)
    }

    console.log('bundle budget: within limits')
  } catch (error) {
    console.error(
      `bundle report failed: ${String(error)}\n` +
        'Run `pnpm build` first — the report reads apps/lab/dist.',
    )
    process.exit(1)
  }
}
